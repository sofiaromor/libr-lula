create or replace function public.update_reading_club_progress(
  p_club_id bigint,
  p_current_chapter integer,
  p_current_page integer,
  p_progress integer default null
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_total_pages integer := 0;
  v_safe_page integer;
  v_safe_progress integer;
begin
  if auth.uid() is null then
    raise exception 'Debes iniciar sesión.';
  end if;

  select greatest(0, coalesce(b.pages, 0))
    into v_total_pages
  from public.reading_clubs c
  left join public.books b on b.id = c.current_book_id
  where c.id = p_club_id;

  v_safe_page := greatest(0, coalesce(p_current_page, 0));
  if v_total_pages > 0 then
    v_safe_page := least(v_safe_page, v_total_pages);
    v_safe_progress := round((v_safe_page::numeric / v_total_pages::numeric) * 100)::integer;
  else
    v_safe_progress := greatest(0, least(100, coalesce(p_progress, 0)));
  end if;

  update public.reading_club_members
  set current_chapter = greatest(1, coalesce(p_current_chapter, 1)),
      current_page = v_safe_page,
      progress = v_safe_progress,
      updated_at = now()
  where club_id = p_club_id
    and user_id = auth.uid()
    and status = 'active';

  if not found then
    raise exception 'No perteneces a este club.';
  end if;

  return true;
end;
$$;

create or replace function public.set_reading_club_member_role(
  p_club_id bigint,
  p_user_id uuid,
  p_role text
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_owner uuid;
begin
  if auth.uid() is null then
    raise exception 'Debes iniciar sesión.';
  end if;

  select owner_id into v_owner from public.reading_clubs where id = p_club_id;
  if v_owner is null then raise exception 'El club no existe.'; end if;
  if v_owner <> auth.uid() then
    raise exception 'Solo la creadora puede gestionar moderadoras.';
  end if;
  if p_user_id = v_owner then
    raise exception 'La creadora conserva siempre su rol.';
  end if;
  if p_role not in ('moderator', 'member') then
    raise exception 'El rol no es válido.';
  end if;

  update public.reading_club_members
  set role = p_role, updated_at = now()
  where club_id = p_club_id
    and user_id = p_user_id
    and status = 'active';

  if not found then raise exception 'La persona no pertenece al club.'; end if;
  return true;
end;
$$;

create or replace function public.remove_reading_club_member(
  p_club_id bigint,
  p_user_id uuid
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_owner uuid;
  v_actor_role text;
begin
  if auth.uid() is null then raise exception 'Debes iniciar sesión.'; end if;

  select owner_id into v_owner from public.reading_clubs where id = p_club_id;
  select role into v_actor_role
  from public.reading_club_members
  where club_id = p_club_id and user_id = auth.uid() and status = 'active';

  if v_actor_role not in ('owner', 'moderator') then
    raise exception 'No tienes permisos para retirar miembros.';
  end if;
  if p_user_id = v_owner then
    raise exception 'La creadora no puede ser expulsada del club.';
  end if;
  if v_actor_role = 'moderator' and exists (
    select 1 from public.reading_club_members
    where club_id = p_club_id and user_id = p_user_id and role = 'moderator'
  ) then
    raise exception 'Solo la creadora puede retirar a otra moderadora.';
  end if;

  delete from public.reading_club_members
  where club_id = p_club_id and user_id = p_user_id;
  return true;
end;
$$;

create or replace function public.delete_reading_club(p_club_id bigint)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then raise exception 'Debes iniciar sesión.'; end if;
  delete from public.reading_clubs
  where id = p_club_id and owner_id = auth.uid();
  if not found then raise exception 'Solo la creadora puede eliminar el club.'; end if;
  return true;
end;
$$;

create or replace function public.update_reading_club_settings(
  p_club_id bigint,
  p_name text,
  p_description text,
  p_visibility text,
  p_banner_url text,
  p_icon_url text,
  p_rules text[]
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then raise exception 'Debes iniciar sesión.'; end if;
  if not public.is_reading_club_admin(p_club_id, auth.uid()) then
    raise exception 'No tienes permisos para editar este club.';
  end if;

  update public.reading_clubs
  set name = left(trim(coalesce(p_name, name)), 80),
      description = trim(coalesce(p_description, description)),
      visibility = case when p_visibility = 'private' then 'private' else 'public' end,
      banner_url = trim(coalesce(p_banner_url, banner_url)),
      icon_url = trim(coalesce(p_icon_url, icon_url)),
      rules = array(
        select left(trim(item.rule), 240)
        from unnest(coalesce(p_rules, array[]::text[])) as item(rule)
        where trim(item.rule) <> ''
        limit 12
      ),
      updated_at = now()
  where id = p_club_id;

  return true;
end;
$$;

-- La política antigua permitía que un miembro alterase su propio rol.
drop policy if exists reading_club_members_update on public.reading_club_members;
create policy reading_club_members_update
on public.reading_club_members for update
to authenticated
using (public.is_reading_club_admin(club_id, auth.uid()))
with check (public.is_reading_club_admin(club_id, auth.uid()));

drop policy if exists reading_club_members_delete on public.reading_club_members;
create policy reading_club_members_delete
on public.reading_club_members for delete
to authenticated
using (
  (user_id = auth.uid() and role <> 'owner')
  or (public.is_reading_club_admin(club_id, auth.uid()) and role <> 'owner')
);

