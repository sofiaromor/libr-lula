-- Evita que una actualización directa cambie la autoría del club.
create or replace function public.reading_club_protect_owner()
returns trigger
language plpgsql
as $$
begin
  if new.owner_id is distinct from old.owner_id then
    raise exception 'La autoría del club no puede cambiarse desde esta operación.';
  end if;
  return new;
end;
$$;

drop trigger if exists reading_club_protect_owner_before_update on public.reading_clubs;
create trigger reading_club_protect_owner_before_update
before update on public.reading_clubs
for each row execute function public.reading_club_protect_owner();

