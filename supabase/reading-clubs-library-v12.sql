-- Backfill: cada club existente recibe un ciclo de lectura actual.
insert into public.reading_club_readings (club_id, book_id, status, started_at)
select c.id, c.current_book_id, 'current', coalesce(c.created_at, now())
from public.reading_clubs c
where c.current_book_id is not null
  and not exists (
    select 1
    from public.reading_club_readings r
    where r.club_id = c.id and r.status = 'current'
  );

update public.reading_clubs c
set current_reading_id = r.id
from public.reading_club_readings r
where r.club_id = c.id
  and r.status = 'current'
  and c.current_reading_id is distinct from r.id;

update public.reading_club_posts p
set reading_id = c.current_reading_id
from public.reading_clubs c
where c.id = p.club_id
  and p.reading_id is null
  and c.current_reading_id is not null;

