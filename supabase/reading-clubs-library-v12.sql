begin;

create table if not exists public.reading_club_readings (
  id bigint generated by default as identity primary key,
  club_id bigint not null references public.reading_clubs(id) on delete cascade,
  book_id text not null references public.books(id) on delete restrict,
  status text not null default 'current' check (status in ('current', 'completed')),
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  closed_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (
    (status = 'current' and finished_at is null)
    or (status = 'completed' and finished_at is not null)
  )
);

create unique index if not exists reading_club_one_current_reading_idx
  on public.reading_club_readings (club_id)
  where status = 'current';

create index if not exists reading_club_readings_history_idx
  on public.reading_club_readings (club_id, finished_at desc)
  where status = 'completed';

create table if not exists public.reading_club_reading_members (
  reading_id bigint not null references public.reading_club_readings(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  role_at_close text not null default 'member' check (role_at_close in ('owner', 'moderator', 'member')),
  progress_at_close integer not null default 0 check (progress_at_close between 0 and 100),
  current_page_at_close integer not null default 0 check (current_page_at_close >= 0),
  current_chapter_at_close integer not null default 1 check (current_chapter_at_close >= 1),
  captured_at timestamptz not null default now(),
  primary key (reading_id, user_id)
);

create index if not exists reading_club_reading_members_user_idx
  on public.reading_club_reading_members (user_id, reading_id);

alter table public.reading_clubs
  add column if not exists current_reading_id bigint;

